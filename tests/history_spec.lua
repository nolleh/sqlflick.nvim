describe("Session history", function()
  local history = require("sqlflick.history")
  before_each(function()
    history.setup({ enabled = false })
    history.setup({ max_entries = 2 })
  end)
  it("bounds newest-first records and exposes independent safe snapshots", function()
    local db = { id = "dev", name = "Dev", database = "app", type = "mysql", password = "secret" }
    history.start("SELECT 1", db)
    local record = history.start("SELECT 2", db)
    history.start("SELECT 3", db)
    history.finish(record, "success")
    local items = history.list()
    assert.equals(2, #items)
    assert.equals("SELECT 3", items[1].sql)
    assert.equals("success", items[2].state)
    assert.is_number(items[2].duration_ms)
    assert.is_nil(items[1].connection.password)
    items[1].connection.name = "changed"
    assert.equals("Dev", history.list()[1].connection.name)
    history.finish(record, "failed")
    assert.equals("success", history.list()[2].state)
  end)
  it("disables retention", function()
    history.setup({ enabled = false })
    assert.is_nil(history.start("SELECT 1", {}))
    assert.same({}, history.list())
    history.finish(nil, "failed")
  end)
end)
